// Cosmetic motion, light, silence and snap holds must never move the outcome stream.
(function () {
  const check = (ok, why) => { if (!ok) throw new Error(why); };
  const tick = s => { for (let i = 0; i < Math.ceil(s * 60); i++) update(1 / 60); };
  RUN.force = 42; checkpoint = null; newRun(null, 'roof'); setState('play'); clearHeld();
  const q = R.roof, fx = floor.effects, rt = floor.ROOF;
  floor.enter('walk');
  let images = 0; const original = g.drawImage;
  g.drawImage = function (...args) { images++; return original.apply(this, args); };
  floor.drawWarp('souls'); g.drawImage = original;
  check(images === 0, 'walk souls are faint glows without sprite outlines');
  const first = fx.slot(0), second = fx.slot(1), base = floor.soulSpot(0);
  check(first.x !== base.x || first.y !== base.y, 'slots are jittered from the even grid');
  tick(1);
  check(first.x !== fx.slot(0).x && first.y !== fx.slot(0).y && second.x !== fx.slot(1).x, 'each soul bobs and sways independently');
  q.t = rt.effects.distant[0]; check(floor.view().ambient > rt.darkAmbient, 'distant lightning raises ambient');
  floor.enter('flash'); const bright = floor.view().ambient; q.t = .2;
  check(floor.view().ambient < bright / 2, 'lightning falls off within a few frames');
  floor.enter('round1');
  const f = { k: 'wisp', sx: 80, sy: 85, x: 80, y: 85, dx: 0, t: 0, dur: 1.05 };
  floor.soulFreed(f, 'carpshit', 'shot');
  const to = f.to; f.t = .5; floor.wispMotion(f);
  check(f.caught && Math.abs(f.y - (85 + (to.y - 85) * .5 / f.dur)) > 1, 'capture follows a curve into its reserved slot');
  const lights = []; const r = { light(...a) { lights.push(a); } };
  floor.lights(r); const orange = lights[0].slice(3);
  q.volley = {}; lights.length = 0; floor.lights(r); const red = lights[0].slice(3);
  q.stall = 1; lights.length = 0; floor.lights(r); const white = lights[0].slice(3);
  check(orange[0] > orange[1] && red[1] < orange[1] && white[1] > orange[1], 'eye light turns orange, angry red and stall white');
  q.volley = null; floor.enter('quiet'); tick(q.accounted + .05);
  check(q.silenced && Snd.track === null, 'quiet cuts the fight music after the last word');
  floor.enter('return'); q.cut = null; tick(.7); lights.length = 0; floor.lights(r);
  check(lights.length > 1, 'flying souls illuminate the wet roof');
  floor.enter('beam'); q.beamU = 0; lights.length = 0; floor.lights(r);
  check(lights.length >= rt.effects.beamLights + 1, 'beam has light along its full length');
  fx.spool(); const time = R.t; tick(1 / 60);
  check(floor.frameHeld() && R.t > time, 'spool hit-stop holds the picture, preserving fight clock and input');
  tick(.06); check(!floor.frameHeld(), 'presentation hit-stop ends after three frames');
  floor.enter('dawn'); tick(.4);
  const rise = R.fx.filter(f => f.roofRise);
  check(rise.length === q.capturedTotal && rise[0].delay !== rise[rise.length - 1].delay, 'all dawn souls rise with staggered starts');
  check(rise[0].y < rise[0].sy && rise[rise.length - 1].y === rise[rise.length - 1].sy, 'dawn souls leave individually');
  q.t = 2; check(floor.view().dawn === 1, 'sunrise warmth reaches full after two seconds');
  const before = JSON.stringify(q), stream = seed; draw(); draw();
  check(JSON.stringify(q) === before && seed === stream, 'motion, shake and lighting draws never change fight state or seed');
  RUN.force = null; checkpoint = null; newRun(); setState('title'); showCard('title');
})();
