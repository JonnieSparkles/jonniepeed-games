// The story, rugged, continue, pause, and the keyboard.
(function () {
  function check(ok, why) { if (!ok) throw new Error(why); }
  const step = s => { for (let i = 0; i < Math.round(s * 60); i++) update(1 / 60); };
  const key = (type, k) => dispatchEvent(new KeyboardEvent(type, { key: k, bubbles: true }));
  try { localStorage.removeItem('unruggabull-ii-story'); } catch (e) {}
  newRun(); setState('title'); showCard('title');
  check(Title.open && card.hidden, 'the title screen is up');
  Title.press('Start');
  check(state === 'intro' && !crawl.hidden && card.hidden, 'the first Start tells the story');
  for (let k = 0; k < 50 && intro.i < 0; k++) step(.1);
  check(intro.i === 0, 'the first still starts once its pictures are in (or after 4 s at most)');
  step(.5);
  check(crawlText.textContent.length > 0 && crawlText.textContent.length < STORY[0].length, 'it types out');
  advanceIntro();
  step(.05);
  check(crawlText.textContent === STORY[0], 'a tap shows the whole line');
  step(5);
  check(intro.i === 0 && !more.hidden && !moreTap.hidden, 'the still waits for a tap, with the arrow and Tap');
  advanceIntro();
  check(intro.i === 1, 'another moves on');
  step(intro.total + 1);
  check(!more.hidden && moreTap.hidden, 'later stills show the arrow without Tap');
  check(UnrugIntro.tap(1, 410, 128, intro.t, intro.plan) === 'armorClank' && intro.i === 1, 'a tap on Loomy blinks it and stays');
  check(UnrugIntro.tap(1, 40, 40, intro.t, intro.plan) === null, 'a tap elsewhere advances');
  // who tells it: the narrator, then line 4 scrambles into p(Loom)'s machine voice, and line 6 hands back to the narrator
  const orange = () => intro.spans.map(e => e.className === 'm');
  introLine(2); step(intro.total + .5);
  check(!orange().some(Boolean) && crawlText.textContent === STORY[2], 'line 3 is all narrator');
  introLine(3); step(intro.total + .5);
  const grew = STORY[3].indexOf('It grew'), o4 = orange();
  check(!o4.slice(0, grew).some(Boolean) && o4.slice(grew).some(Boolean) && crawlText.textContent === STORY[3], 'line 4 scrambles into p(Loom) at "It grew up so fast"');
  introLine(4); step(intro.total + .5);
  check(orange().every(Boolean), 'p(Loom) tells line 5');
  const even = Snd.talkTimes('ab cd', 'machine').times;
  check(Math.abs((even[1] - even[0]) - (even[2] - even[1])) < 1e-9, 'the machine voice is dead even');
  introLine(5); step(intro.total + .5);
  const back = STORY[5].indexOf('So Unruggabull'), o6 = orange(), tail = STORY[5].indexOf('Sharp ones');
  check(o6.slice(0, back).every(Boolean) && !o6.slice(tail).some(Boolean) && crawlText.textContent === STORY[5], 'p(Loom) reads the books, the narrator takes the hero\'s move');
  introLine(STORY.length - 1); step(intro.total + .5);
  advanceIntro();
  check(state === 'intro' && intro.out === 0 && storySeen(), 'the last tap starts the way out, the story seen');
  advanceIntro();
  check(intro.out === 0, 'taps during the way out do nothing');
  step(OUT * .5);
  check(state === 'intro' && intro.out > 0, 'the doorway light is still filling the picture');
  step(OUT * .5 + .1);
  check(state === 'play' && crawl.hidden && fadeIn && R.stage === 'stairs', 'then the stairwell opens out of the light');
  step(FADE + .1);
  check(!fadeIn, 'and the light clears');
  setState('title'); showCard('title');
  check(Title.open, 'the title again once the story has been seen');
  Title.press('Start');
  check(state === 'intro' && !crawl.hidden, 'every Start plays the story');
  for (let k = 0; k < 50 && intro.i < 0; k++) step(.1);
  key('keydown', 'Escape');
  check(state === 'play' && crawl.hidden && storySeen() && !fadeIn, 'Escape skips to the stairwell, with no fade');
  check(R.stage === 'stairs' && floor.Q.si === 0 && !floor.Q.katana, 'the story ends at the foot of the stairs, no katana yet');
  startRun('floor13');
  check(R.banner && R.banner.text === 'THE 13TH FLOOR' && R.banner.then.text === 'FREE ' + TUNE.goal + ' SOULS', 'the floor opens with its goal');

  RUN.force = 404; startRun();
  for (let i = 0; i < 5; i++) { bull.inv = 0; hurtBull(1); }
  check(R.phase === 'dead' && R.hearts === 0, 'five hits and you are rugged');
  step(TUNE.deadWait + .3);
  check(state === 'over' && Cards.kind === 'rugged' && Cards.labels().join() === 'Retry,Quit' && Cards.info.back === 'THE DOOR', 'UNIT RUGGED: Retry or Quit');
  Cards.press('Retry');
  check(state === 'over' && Cards.confirming && Cards.labels().join() === 'Retry,Back', 'the first Retry asks: it will not count on the leaderboard');
  Cards.press('Back');
  check(!Cards.confirming && Cards.labels().join() === 'Retry,Quit', 'Back returns to the card');
  Cards.press('Retry'); Cards.press('Retry');
  check(state === 'play' && R.hearts === TUNE.hearts && R.souls === 0 && R.phase === 'hall', 'continue starts the floor over');

  key('keydown', 'p');
  check(state === 'pause' && Cards.kind === 'pause' && Cards.labels()[0] === 'Resume', 'P pauses');
  const t = R.t; step(1);
  check(R.t === t, 'nothing moves while paused');
  key('keydown', 'Escape');
  check(state === 'play' && card.hidden && !Cards.open, 'Escape resumes');

  bull.u = 0; key('keydown', 'ArrowLeft'); step(.2); key('keyup', 'ArrowLeft');
  check(bull.u < -.2, 'arrow keys move');
  const u = bull.u; step(.2);
  check(bull.u === u, 'and stop on release');
  key('keydown', ' '); update(1 / 60);
  check(bull.jh > 0, 'Space jumps');
  step(1); bull.cd = 0; key('keydown', 'k'); update(1 / 60);
  check(bull.slash >= 0, 'K slashes');
  R.events.shots = 0; R.fireT = 0; key('keydown', 'j'); step(.5);
  check(R.events.shots >= 2, 'J shoots while held');
  key('keyup', 'j'); R.events.shots = 0; step(.5);
  check(R.events.shots === 0, 'and stops on release');
  key('keydown', 'ArrowUp'); step(.1);
  check(bull.jh > 0, 'Up jumps');
  step(1);
  const code = (type, k, c) => dispatchEvent(new KeyboardEvent(type, { key: k, code: c, bubbles: true }));
  R.events.shots = 0; R.fireT = 0; R.charge = TUNE.charges; code('keydown', 'Shift', 'ShiftLeft'); step(.5); code('keyup', 'Shift', 'ShiftLeft');
  check(R.events.shots >= 2, 'Shift shoots');
  R.events.shots = 0; R.fireT = 0; code('keydown', "'", 'Quote'); step(.3); code('keyup', "'", 'Quote');
  check(R.events.shots >= 1, "' shoots");
  bull.cd = 0; bull.slash = -1; code('keydown', 'Enter', 'Enter'); update(1 / 60);
  check(bull.slash >= 0, 'Enter slashes');
  bull.cd = 0; bull.slash = -1; code('keydown', 'K', 'KeyK'); update(1 / 60);
  check(bull.slash >= 0, 'K slashes even with Shift held');
  pauseGame(); Cards.press('Restart floor');
  check(state === 'play' && R.t < .1, 'restart floor from the pause card');
})();
