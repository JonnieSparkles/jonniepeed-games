"""Unruggabull's recorded lines, crushed to chip voice: python3 tools/unruggabull-ii/voice/voice.py

Writes site/unruggabull-ii/voice.js (window.UnrugVoice) from the recordings beside this file. Every line goes through
the same recipe so they sound alike: mono, trimmed to the words and their ring-out, levelled, squashed with tanh so the
quiet parts survive, then 8 kHz and 6-bit (Chip voice, picked by the owner on the audition page, Oct 14). The samples
are packed four to three bytes and base64'd; audio.js unpacks them and plays each sample held until the next, as a chip
would. Needs ffmpeg and numpy. Record new lines at about the same distance and loudness as lets-go.mp3."""
import base64
import subprocess
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[2] / 'site' / 'unruggabull-ii' / 'voice.js'
RATE, BITS, DRIVE = 8000, 6, 2.4
# key (as in game.js's LINES): file, start and end in seconds (the words plus their ring-out), where the fade-out starts
LINES = {
    'go': ('lets-go.mp3', .44, 2.0, 1.59),   # from unruggabull-the-game, the first game's "Let's go!"
}


def crush(name, start, end, fade):
    af = f'atrim={start}:{end},afade=t=in:d=0.01,afade=t=out:st={fade - start:.3f}:d={end - fade:.3f}:curve=qsin'
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(HERE / name), '-ac', '1', '-ar', str(RATE), '-af', af, '-f', 'f32le', '-'],
                         check=True, capture_output=True).stdout
    x = np.frombuffer(raw, np.float32).astype(np.float64)
    x = x / np.abs(x).max() * .95
    x = np.tanh(DRIVE * x) / np.tanh(DRIVE)
    q = np.clip(np.round((x + 1) / 2 * 63), 0, 63).astype(np.uint32)   # 0..63, 32 is silence
    q = np.concatenate([q, np.full(-len(q) % 4, 32, np.uint32)])
    w = q[0::4] << 18 | q[1::4] << 12 | q[2::4] << 6 | q[3::4]           # four 6-bit samples in three bytes
    packed = np.stack([w >> 16 & 255, w >> 8 & 255, w & 255], 1).astype(np.uint8).tobytes()
    return base64.b64encode(packed).decode(), len(q)


out = ['// Unruggabull\'s recorded lines, as chip voice. Generated by tools/unruggabull-ii/voice/voice.py; edit the recordings there.',
       f'window.UnrugVoice = {{ rate: {RATE}, bits: {BITS}, lines: {{']
for key, (name, start, end, fade) in LINES.items():
    data, n = crush(name, start, end, fade)
    out.append(f'  {key}: {{ n: {n}, data: "{data}" }},')
    print(key, n, 'samples', round(n / RATE, 2), 's', len(data), 'bytes in code')
out.append('} };\n')
OUT.write_text('\n'.join(out))
print(OUT)
