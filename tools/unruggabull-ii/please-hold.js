// Please Hold for the quiet ride and the 48th Floor lobby. Writes only pleaseHold; Horns Up stays byte for byte.
// A is TRACKS.hold's first section from long-ride/synth.js, compiled note for note on the classic voice.
// B answers it with four more bars, using the same triangle lead, seventh-chord pads, bass and rim taps.
//   node tools/unruggabull-ii/please-hold.js
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..', '..'), box = {};
vm.createContext(box);
vm.runInContext(fs.readFileSync(path.join(__dirname, 'long-ride', 'synth.js'), 'utf8') +
  '\n;this.TRACKS = TRACKS; this.compile = compile;', box);
const first = box.TRACKS.hold.sections[0]; // No 184 BPM snap section on this ride.
const second = Object.assign({}, first, {
  chords: ['Cmaj7', 'Em7', 'Dm7', 'Cmaj7'],
  lead: Object.assign({}, first.lead, {
    notes: 'G5 - - - E5 - - - D5 - E5 - G5 - - - | B5 - - - G5 - - - E5 - G5 - D5 - - - | A5 - - - F5 - - - E5 - D5 - C5 - A4 - | D5 - - - E5 - - - C5 - - - - - - -'
  })
});
const NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
const name = m => NAMES[((m % 12) + 12) % 12] + (Math.floor(m / 12) - 1);
function bars(tokens) {
  const b = [];
  for (let i = 0; i < tokens.length; i += 16) b.push(tokens.slice(i, i + 16).join(' '));
  return b.join(' | ');
}
function pattern(sec) {
  const c = box.compile(sec), labels = [['lead', 'lead'], ['arp1', 'arp'], ['bass', 'bass']], channels = {};
  if (c.chans.length !== labels.length || c.steps !== 64 || sec.bpm !== 100) throw new Error('expected four-bar muzak');
  c.chans.forEach((ch, i) => {
    const tokens = [];
    for (let s = 0; s < c.steps;) {
      const evs = ch.byStep[s];
      if (!evs) { tokens.push('.'); s++; continue; }
      const e = evs[0], len = Math.min(e.len, c.steps - s), rest = evs.slice(1).map(x => name(x.m));
      if (!rest.length && e.g == null) { tokens.push(name(e.m)); for (let k = 1; k < len; k++) tokens.push('-'); }
      else {
        const o = { note: name(e.m), len };
        if (rest.length) o.chord = rest;
        if (e.g != null) o.gate = e.g;
        tokens.push(o);
      }
      s += len;
    }
    const cfg = { stem: labels[i][1], synth: 'classic', wave: ch.wave, vol: ch.vol };
    if (ch.gate) cfg.gate = ch.gate;
    if (ch.vib) cfg.vib = true;
    cfg.notes = tokens.every(x => typeof x === 'string') ? bars(tokens) : tokens;
    channels[labels[i][0]] = cfg;
  });
  channels.drums = { stem: 'drums', synth: 'classic', wave: 'noise', notes: bars(c.drums) };
  return { bars: 4, bpm: 100, channels };
}
const track = { name: 'Please Hold', key: 'C', bpm: 100, swing: 0, loop: 0, order: ['A', 'B'],
  stems: ['lead', 'arp', 'bass', 'drums'], patterns: { A: pattern(first), B: pattern(second) } };
const body = JSON.stringify(track, null, 1).replace(/\n\s*/g, ' ').replace(/"(\w+)":/g, '$1:').replace(/"/g, "'");
const lines = body.replace(/ (A|B): \{ bars/g, '\n    $1: { bars')
  .replace(/ (lead|arp1|bass|drums): \{ stem/g, '\n      $1: { stem');
const file = path.join(root, 'site', 'unruggabull-ii', 'music-elevator.js'), src = fs.readFileSync(file, 'utf8');
const at = src.indexOf('// Horns Up');
if (at < 0) throw new Error('no Horns Up block');
fs.writeFileSync(file, '// Please Hold: the storyboard\'s 100 BPM muzak and a second four-bar phrase, on the classic voice.\n' +
  '// Generated by tools/unruggabull-ii/please-hold.js; edit the script and rerun. A then B loop (19.2 s), no snap.\n' +
  'window.UnrugElevatorMusic = { pleaseHold: ' + lines + ' };\n\n' + src.slice(at));
console.log('pleaseHold: A (storyboard) + B (answer), 4 bars each, 100 BPM, classic voice');
