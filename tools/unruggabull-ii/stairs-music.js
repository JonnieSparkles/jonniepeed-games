// Writes the stairwell's music into site/unruggabull-ii/music-stairs.js as plain track objects.
// Usage, from the repo root: node tools/unruggabull-ii/stairs-music.js
// The tracks are written in tools/unruggabull-ii/stairwell/music-stairs.js (the design page's takes); this picks the two
// Jonnie chose (docs/games/unruggabull-ii/stairwell-plan.md): Flight Risk for the climb ("stairs": drums, bass and lead;
// + harmony after the Rugmergency; + power and the build for the last flights) and "Over the Top, up the stairs" for
// the katana ("stairsFanfare", a one-shot that rests on a silent bar). "stairsIn" is Flight Risk with a bridge from the
// title theme in front of it (below).
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const box = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, 'stairwell/music-stairs.js'), 'utf8'), box);
const M = box.window.UnrugStairsMusic;
const stairs = Object.assign({}, M.CUES.flight.tracks.stairFlight, { name: 'The stairwell · Flight Risk' });
const fanfare = Object.assign({}, M.FANFARES[3](M.KEYSHIFT.flight), { name: 'The stairwell · Over the Top, up the stairs' });
// From the title (the album page's handoff, Oct 17): a two-bar bridge X in front of Flight Risk, for a stairwell that
// starts with the title theme still playing. The theme's D as a power chord, then C and B under a snare roll and a run up
// the scale, so Flight Risk's first E lands as the answer (D minor's home chord as E minor's flat seven, then its five).
// "stairsIn" plays X once, then loops Flight Risk's own A; its stems are Flight Risk's, so the layers work the same.
const rest = n => Array(n).fill('.').join(' ');
const fifth = { D3: ['A3', 'D4'], C3: ['G3', 'C4'], B2: ['F#3', 'B3'] };
const pw = (note, len, gate) => ({ note, chord: fifth[note], len, gate: gate == null ? .95 : gate });
const X = { bars: 2, channels: {
  gtr: { stem: 'bass', wave: 'sawtooth', drive: true, vol: .045, notes: [pw('D3', 12), pw('D3', 2, .4), pw('D3', 2, .4), pw('C3', 4), pw('C3', 2, .4), pw('C3', 2, .4), pw('B2', 8)] },
  bass: { stem: 'bass', wave: 'triangle', vol: .3, gate: .85, notes: 'D2 - - - - - - - - - - - D2 - D2 - | C2 - - - C2 - C2 - B1 - - - - - - -' },
  drums: { stem: 'drums', wave: 'noise', vol: .52, notes: 'K . . . T . . . T . T . T T T T | S . S . S . S . S S S S S S S S' },
  crash: { stem: 'drums', wave: 'noise', vol: .4, notes: 'c ' + rest(15) + ' | ' + rest(16) },
  lead: { stem: 'lead', wave: 'pulse', duty: .5, vol: .08, gate: .9, notes: rest(16) + ' | . . . . . . . . B4 C5 D5 E5 F#5 G5 A5 B5', echo: { delay: .17, feedback: .2, repeats: 1 } }
} };
const tracks = { stairs, stairsFanfare: fanfare };
const out = '// The stairwell\'s music: Flight Risk, Flight Risk from the title (a bridge in front of it) and the katana\'s fanfare.\n' +
  '// Plain track objects; load before audio.js.\n' +
  '// Generated by tools/unruggabull-ii/stairs-music.js from tools/unruggabull-ii/stairwell/music-stairs.js (edit them there).\n' +
  'window.UnrugStairsMusic = ' + JSON.stringify(tracks, null, 2) + ';\n' +
  '// stairsIn: Flight Risk with the bridge from the title theme (X) in front of its own A, which it shares.\n' +
  'window.UnrugStairsMusic.stairsIn = Object.assign({}, window.UnrugStairsMusic.stairs, { name: ' + JSON.stringify('The stairwell · Flight Risk, from the title') +
  ', order: ["X", "A"], loop: 1,\n  patterns: { X: ' + JSON.stringify(X) + ', A: window.UnrugStairsMusic.stairs.patterns.A } });\n';
fs.writeFileSync(path.join(__dirname, '../../site/unruggabull-ii/music-stairs.js'), out);
console.log('wrote site/unruggabull-ii/music-stairs.js:', Object.keys(tracks).concat('stairsIn').join(', '),
  '· the fanfare runs', M.seconds(fanfare).toFixed(2), 's');
