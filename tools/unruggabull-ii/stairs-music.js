// Writes the stairwell's music into site/unruggabull-ii/music-stairs.js as plain track objects.
// Usage, from the repo root: node tools/unruggabull-ii/stairs-music.js
// The tracks are written in tools/unruggabull-ii/stairwell/music-stairs.js (the design page's takes); this picks the two
// Jonnie chose (docs/games/unruggabull-ii/stairwell-plan.md): Flight Risk for the climb ("stairs": drums, bass and lead;
// + harmony after the Rugmergency; + power and the build for the last flights) and "Over the Top, up the stairs" for
// the katana ("stairsFanfare", a one-shot that rests on a silent bar).
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const box = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, 'stairwell/music-stairs.js'), 'utf8'), box);
const M = box.window.UnrugStairsMusic;
const stairs = Object.assign({}, M.CUES.flight.tracks.stairFlight, { name: 'The stairwell · Flight Risk' });
const fanfare = Object.assign({}, M.FANFARES[3](M.KEYSHIFT.flight), { name: 'The stairwell · Over the Top, up the stairs' });
const out = '// The stairwell\'s music: Flight Risk and the katana\'s fanfare. Plain track objects; load before audio.js.\n' +
  '// Generated by tools/unruggabull-ii/stairs-music.js from tools/unruggabull-ii/stairwell/music-stairs.js (edit them there).\n' +
  'window.UnrugStairsMusic = ' + JSON.stringify({ stairs, stairsFanfare: fanfare }, null, 2) + ';\n';
fs.writeFileSync(path.join(__dirname, '../../site/unruggabull-ii/music-stairs.js'), out);
console.log('wrote site/unruggabull-ii/music-stairs.js:', Object.keys({ stairs, stairsFanfare: fanfare }).join(', '),
  '· the fanfare runs', M.seconds(fanfare).toFixed(2), 's');
